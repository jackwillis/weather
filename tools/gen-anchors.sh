# Regenerate src/tls/anchors.h from src/tls/roots.pem with BearSSL's brssl.
# usage: tools/gen-anchors.sh BRSSL > src/tls/anchors.h
BRSSL=${1:?usage: gen-anchors.sh path/to/brssl}
cd "$(dirname "$0")/.." || exit 1
echo "// GENERATED by tools/gen-anchors.sh from src/tls/roots.pem (ISRG Root X1, ISRG Root X2, HARICA TLS RSA Root CA 2021). Do not edit."
echo "// Refreshing these is a release task: edit the PEM, run 'make anchors', commit both."
"$BRSSL" ta src/tls/roots.pem
