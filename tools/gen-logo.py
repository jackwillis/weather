"""Reduce the 512x256 logo to a 1-bit bitmap for the About boxes: src/app/logo.hpp.

usage: tools/gen-logo.py [--preview out.png]
Black ink on white, area-averaged down to WIDTH x HEIGHT, then thresholded. Rows are MSB-first, padded to whole bytes
(the layout X11 bitmaps want when bit order is MSB, and the classic Macintosh BitMap uses). 1 = black.
"""
import sys
from PIL import Image

SRC = "assets/logo/whatitbelike-512x256.png"
OUT = "src/app/logo.hpp"
WIDTH, HEIGHT = 160, 80
THRESHOLD = 150   # darker than this (0 black..255 white) becomes ink; keeps thin serifs

im = Image.open(SRC).convert("RGBA")
bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
bg.alpha_composite(im)
gray = bg.convert("L").resize((WIDTH, HEIGHT), Image.LANCZOS)
bits = gray.point(lambda v: 1 if v < THRESHOLD else 0)

rowbytes = (WIDTH + 7) // 8
data = bytearray()
for y in range(HEIGHT):
    for bx in range(rowbytes):
        b = 0
        for k in range(8):
            x = bx * 8 + k
            b = (b << 1) | (bits.getpixel((x, y)) if x < WIDTH else 0)
        data.append(b)

lines = []
for i in range(0, len(data), 16):
    lines.append("\t" + ", ".join("0x%02x" % v for v in data[i:i + 16]) + ",")
with open(OUT, "w") as f:
    f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (c) 2026 Jack Willis\n")
    f.write("// Generated by tools/gen-logo.py from %s. Do not edit.\n" % SRC)
    f.write("// 1-bit logo, %dx%d, MSB first, rows padded to %d bytes, 1 = black.\n#pragma once\n#include <cstdint>\n\nnamespace wx {\n\n" % (WIDTH, HEIGHT, rowbytes))
    f.write("inline constexpr int kLogoW = %d, kLogoH = %d, kLogoRowBytes = %d;\n" % (WIDTH, HEIGHT, rowbytes))
    f.write("inline constexpr uint8_t kLogoBits[] = {\n" + "\n".join(lines) + "\n};\n\n} // namespace wx\n")
if "--preview" in sys.argv:
    p = sys.argv[sys.argv.index("--preview") + 1]
    bits.point(lambda v: 0 if v else 255).resize((WIDTH * 4, HEIGHT * 4), Image.NEAREST).save(p)
print("wrote", OUT, len(data), "bytes")
